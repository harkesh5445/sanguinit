<!-- Optimized scroll-to-top functionality -->
<script>
   document.addEventListener('DOMContentLoaded', function() {
      const scrollToTopBtn = document.querySelector('.scroll-to-top');

      if (scrollToTopBtn) {
         scrollToTopBtn.addEventListener('click', function(e) {
            e.preventDefault();

            const contactForm = document.getElementById('contact-form');
            if (contactForm) {
               const rect = contactForm.getBoundingClientRect();
               const offset = window.innerHeight * 0.15;
               const targetPosition = window.pageYOffset + rect.top - offset;

               // Smooth scroll with fallback for older browsers
               if (window.requestAnimationFrame && window.scrollTo) {
                  window.scrollTo({
                     top: Math.max(0, targetPosition),
                     behavior: 'smooth'
                  });
               } else {
                  // Fallback for older browsers
                  document.documentElement.scrollTop = Math.max(0, targetPosition);
               }

               // Focus first input after scroll
               setTimeout(() => {
                  const firstInput = contactForm.querySelector('input[name="name"]');
                  if (firstInput) {
                     firstInput.focus();
                  }
               }, 800);
            }
         });
      }
   });
</script>
