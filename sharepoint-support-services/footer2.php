<!-- Enhanced Preloader Script with Dynamic Messages and Progress -->
<script>
   // Dynamic loading messages with better timing
   const loadingMessages = [
      'Initializing your experience<span class="loading-dots">...</span>',
      'Loading cutting-edge solutions<span class="loading-dots">...</span>',
      'Preparing digital excellence<span class="loading-dots">...</span>',
      'Setting up innovation<span class="loading-dots">...</span>',
      'Crafting your journey<span class="loading-dots">...</span>',
      'Finalizing details<span class="loading-dots">...</span>',
      'Almost ready<span class="loading-dots">...</span>'
   ];

   let messageIndex = 0;
   let messageInterval;
   let progressInterval;
   let currentProgress = 0;

   // Function to cycle through loading messages
   function cycleLoadingMessages() {
      const messageElement = document.getElementById('loadingMessage');
      if (messageElement && messageIndex < loadingMessages.length) {
         messageElement.style.opacity = '0';
         setTimeout(() => {
            messageElement.innerHTML = loadingMessages[messageIndex];
            messageElement.style.opacity = '1';
            messageIndex++;
         }, 200);
      }
   }

   // Function to simulate progress
   function updateProgress() {
      const progressFill = document.querySelector('.progress-fill');
      if (progressFill && currentProgress < 100) {
         currentProgress += Math.random() * 15 + 5; // Random increment between 5-20
         if (currentProgress > 100) currentProgress = 100;
         progressFill.style.width = currentProgress + '%';
      }
   }

   // Enhanced typewriter effect for company name
   function typewriterEffect() {
      const text = 'Sanguine IT';
      const element = document.querySelector('.loading-text');
      if (element) {
         element.innerHTML = '';
         let i = 0;
         const timer = setInterval(() => {
            if (i < text.length) {
               element.innerHTML += text.charAt(i);
               i++;
            } else {
               clearInterval(timer);
               element.innerHTML += '<span style="animation: blink 1s infinite;">|</span>';
            }
         }, 100);
      }
   }

   // Start all animations
   document.addEventListener('DOMContentLoaded', function() {
      // Start typewriter effect
      setTimeout(typewriterEffect, 800);

      // Start message cycling
      setTimeout(() => {
         messageInterval = setInterval(cycleLoadingMessages, 900);
      }, 2200);

      // Start progress simulation
      setTimeout(() => {
         progressInterval = setInterval(updateProgress, 300);
      }, 2800);
   });

   // Hide preloader when page is fully loaded
   window.addEventListener('load', function() {
      const preloader = document.getElementById('preloader');
      if (preloader) {
         // Clear all intervals
         if (messageInterval) clearInterval(messageInterval);
         if (progressInterval) clearInterval(progressInterval);

         // Complete progress bar
         const progressFill = document.querySelector('.progress-fill');
         if (progressFill) {
            progressFill.style.width = '100%';
         }

         // Show completion message
         const messageElement = document.getElementById('loadingMessage');
         if (messageElement) {
            setTimeout(() => {
               messageElement.style.opacity = '0';
               setTimeout(() => {
                  messageElement.innerHTML = 'Welcome to Sanguine IT<span class="loading-dots">!</span>';
                  messageElement.style.opacity = '1';
               }, 200);
            }, 300);
         }

         // Add a small delay to show completion
         setTimeout(() => {
            preloader.classList.add('fade-out');
            // Remove loading class from body to show content
            document.body.classList.remove('loading');
            setTimeout(() => {
               preloader.style.display = 'none';
            }, 800);
         }, 1000);
      }
   });

   // Fallback: Hide preloader after maximum wait time
   setTimeout(() => {
      const preloader = document.getElementById('preloader');
      if (preloader && !preloader.classList.contains('fade-out')) {
         // Clear all intervals
         if (messageInterval) clearInterval(messageInterval);
         if (progressInterval) clearInterval(progressInterval);

         // Complete progress and show final message
         const progressFill = document.querySelector('.progress-fill');
         if (progressFill) {
            progressFill.style.width = '100%';
         }

         const messageElement = document.getElementById('loadingMessage');
         if (messageElement) {
            messageElement.innerHTML = 'Ready to explore<span class="loading-dots">!</span>';
         }

         setTimeout(() => {
            preloader.classList.add('fade-out');
            // Remove loading class from body to show content
            document.body.classList.remove('loading');
            setTimeout(() => {
               preloader.style.display = 'none';
            }, 800);
         }, 500);
      }
   }, 5000); // Maximum 5 seconds for better UX
</script>
