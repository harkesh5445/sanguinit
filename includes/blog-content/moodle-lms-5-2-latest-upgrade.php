<h2 id="upgrade-path">Upgrade Path and Risk Controls</h2>

<p class="lh">A production Moodle upgrade should follow a repeatable playbook:</p>

<ol class="blog-article-list blog-article-list--ordered">
    <li>Clone production to a staging environment with anonymized data where required.</li>
    <li>Run automated and manual regression tests on enrollments, quizzes, certificates, and payments (if applicable).</li>
    <li>Validate backup/restore procedures and define rollback criteria.</li>
    <li>Communicate maintenance windows to learners and support desks.</li>
    <li>Monitor queues, cron tasks, and error logs for 48–72 hours post-launch.</li>
</ol>

<p class="lh">Plugin compatibility is the most common source of delay. Maintain a plugin inventory with owners and upgrade notes so obsolete extensions are retired instead of blocking releases indefinitely.</p>

