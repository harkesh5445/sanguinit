<p class="lh">Mobile apps handle credentials, personal data, and business-critical workflows on devices you do not control. Security must be designed in — not bolted on before store submission.</p>

<h2>Threats to plan for</h2>
<p class="lh">Insecure local storage, broken API authentication, reverse-engineered binaries, and man-in-the-middle attacks on public networks are common findings in app audits.</p>

<h2>Secure development workflow</h2>
<p class="lh">Use certificate pinning where appropriate, encrypt sensitive data at rest, enforce OAuth or token-based auth, and run SAST/DAST in CI. Never embed secrets in client code.</p>

