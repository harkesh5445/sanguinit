<h2 id="foundation">Foundation before promotion</h2>
<p class="eb-p">Polish your store listing (ASO): clear title, benefit-driven subtitle, screenshots that show outcomes, and a short preview video. Instrument analytics events for activation, retention, and referral so you know which tactics work.</p>

<h2 id="ten-tactics">Ten free marketing tactics</h2>
<ol class="eb-list eb-list-ordered">
    <li>Optimize App Store and Play Store metadata with intent-based keywords.</li>
    <li>Publish launch posts in niche communities (not spam—provide value first).</li>
    <li>Guest articles on industry blogs with a single clear CTA.</li>
    <li>Partner cross-promotions with complementary (non-competing) apps.</li>
    <li>Email your existing customer base with a focused use-case story.</li>
    <li>Create short demo videos for LinkedIn and YouTube.</li>
    <li>Encourage in-app referrals with simple share mechanics.</li>
    <li>Collect and respond to reviews to improve store ranking signals.</li>
    <li>Speak at webinars or local meetups with live product demos.</li>
    <li>Repurpose help content into SEO-friendly support articles.</li>
</ol>

<h2 id="measure">Measure what matters</h2>
<p class="eb-p">Track cost per activated user, day-7 retention, and organic install share. Double down on channels that bring engaged users—not just installs.</p>

