<p class="eb-p">SanguineIT runs hybrid and offshore delivery daily. This handbook captures practices that keep product owners, architects, and engineers aligned across regions.</p>

<h2 id="team-design">Team design</h2>
<p class="eb-p">Define a single source of truth for backlog, designs, and documentation. Overlap core hours for standups and planning. Assign clear roles: product owner decisions, tech lead architecture, scrum master facilitation.</p>

<h2 id="ceremonies">Ceremonies that work remotely</h2>
<p class="eb-p"><strong>Daily standup</strong> — 15 minutes, blockers only, async updates when needed.</p>
<p class="eb-p"><strong>Sprint planning</strong> — Pre-refined stories; confirm capacity and dependencies live.</p>
<p class="eb-p"><strong>Review & retro</strong> — Demo working software; one improvement action per sprint.</p>
<p class="eb-p">Record decisions in writing. Use video for complex discussions; chat for quick clarifications.</p>

<h2 id="quality">Quality and release discipline</h2>
<p class="eb-p">Automate tests in CI, enforce pull request reviews, and maintain staging parity with production. Definition of done includes documentation, monitoring, and rollback plans.</p>

