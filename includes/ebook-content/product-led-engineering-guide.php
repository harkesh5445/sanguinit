<p class="eb-p">This guide is for engineering managers, product owners, and delivery leads who want clearer alignment between discovery, build, and measurement.</p>

<h2 id="discovery">Discovery and outcomes</h2>
<p class="eb-p">Start with outcomes: reduce checkout abandonment, shorten onboarding time, or improve API reliability. Write problem statements before solutions. Use lightweight discovery—interviews, journey maps, and prototype tests—to validate assumptions in days, not months.</p>

<h2 id="delivery">Delivery practices</h2>
<p class="eb-p">Break work into thin vertical slices deployable to production behind flags. Maintain a healthy backlog with clear acceptance criteria. Pair product and engineering in refinement; define non-functional requirements (performance, security, accessibility) up front.</p>

<h2 id="metrics">Metrics that matter</h2>
<ul class="eb-list">
    <li>Outcome metrics: conversion, retention, task success rate.</li>
    <li>Health metrics: error rate, latency, deployment frequency.</li>
    <li>Flow metrics: cycle time, WIP limits, escaped defects.</li>
</ul>
<p class="eb-p">Review metrics in sprint reviews; pivot when data contradicts the roadmap hypothesis.</p>

