<h2 id="engagement-models">Engagement models</h2>
<p class="eb-p"><strong>Dedicated team</strong> — Best when you need ongoing capacity with your backlog and tools. You manage priorities; the partner supplies engineers integrated into your ceremonies.</p>
<p class="eb-p"><strong>Project outsourcing</strong> — Best for defined scope with clear acceptance criteria. Requires strong specification and change control.</p>
<p class="eb-p"><strong>Managed delivery</strong> — Partner owns outcomes with shared KPIs. Suits programs where internal PM capacity is limited.</p>

<h2 id="evaluation-criteria">Evaluation criteria</h2>
<ul class="eb-list">
    <li><strong>Domain expertise:</strong> Case studies in your stack (Magento, Sitefinity, .NET, mobile, cloud).</li>
    <li><strong>Engineering quality:</strong> Code review standards, test automation, and definition of done.</li>
    <li><strong>Security:</strong> SOC-aligned practices, access control, and secure SDLC.</li>
    <li><strong>Communication:</strong> Time-zone overlap, English proficiency, and escalation paths.</li>
    <li><strong>Retention:</strong> Low churn on accounts similar to yours.</li>
</ul>

<h2 id="red-flags">Red flags to avoid</h2>
<p class="eb-p">Be cautious when vendors promise unrealistic timelines, refuse reference calls, lack version control discipline, or blur lines between environments. Fixed bids without discovery often hide change-order risk.</p>

