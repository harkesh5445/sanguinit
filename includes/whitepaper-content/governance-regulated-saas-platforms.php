<h2 id="control-framework">Control framework</h2>
<p class="wp-p">Map controls to SOC 2 Trust Services Criteria or ISO 27001 annexes. Implement encryption in transit and at rest, secrets management, vulnerability management, and secure SDLC gates. Maintain evidence repositories linked to change tickets.</p>

