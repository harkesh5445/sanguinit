<h2 id="roi-model">ROI model</h2>
<p class="wp-p">Quantify: accelerated campaign launches, conversion lift from performance, developer productivity, and reduced duplicate logic. Offset: additional headcount, licensing, observability, and contract testing across services.</p>

<h2 id="implementation-risks">Implementation risks</h2>
<p class="wp-p">Common pitfalls include under-specified APIs, inconsistent cart state across channels, and SEO gaps in SPA implementations. Mitigate with BFF layers, SSR where needed, and end-to-end test suites.</p>

