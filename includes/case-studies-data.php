function case_study_url($slug)
{
    return 'case-study-single.php?slug=' . rawurlencode($slug);
}

function get_case_study($slug)
{
    global $caseStudies;
    return isset($caseStudies[$slug]) ? $caseStudies[$slug] : null;
}

function get_case_studies_by_type($type)
{
    global $caseStudiesListingOrder;
    $items = [];
    foreach ($caseStudiesListingOrder as $slug) {
        $item = get_case_study($slug);
        if ($item && isset($item['type']) && $item['type'] === $type) {
            $items[$slug] = $item;
        }
    }
    return $items;
}

function get_case_study_html($slug)
{
    $study = get_case_study($slug);
    if (!$study) {
        return '';
    }
    $contentFile = __DIR__ . '/case-study-content/' . $slug . '.php';
    if (is_readable($contentFile)) {
        ob_start();
        include $contentFile;
        return ob_get_clean();
    }
    $summary = htmlspecialchars($study['summary'], ENT_QUOTES, 'UTF-8');
    return '<p class="lh">' . $summary . '</p><p class="lh"><a href="contact-us.php">Contact SanguineIT</a> for a similar engagement assessment.</p>';
}
